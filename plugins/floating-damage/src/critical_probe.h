inline bool CriticalLayoutMatches(std::uintptr_t base) noexcept {
    const auto matches=[&](std::uintptr_t rva,const auto& expected){
        std::array<unsigned char,sizeof(expected)> actual{};
        return Bytes(base+rva,actual.data(),actual.size()) && std::memcmp(actual.data(),expected,actual.size())==0;
    };
    return matches(CriticalBuilderRva,CriticalBuilderBytes) && matches(PassiveCriticalRva,PassiveCriticalBytes) &&
        matches(DeadlyStrikeRva,DeadlyStrikeBytes) && matches(CriticalWriterRva,CriticalWriterBytes);
}
