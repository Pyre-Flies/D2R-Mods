"""Generate the C++ witness header from the canonical native ledger."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(profile):
    lines = ["// Generated by tools/generate_profile.py; edit native-profile.json.",
             "#pragma once", "#include <array>", "#include <cstdint>",
             "namespace DayNight::Profile {"]
    for key in ("host", "core"):
        lines.append(f'inline constexpr char {key.title()}Hash[] = "{profile[key]["sha256"]}";')
    for key, value in profile["constants"].items():
        value = int(value, 0) if isinstance(value, str) else value
        lines.append(f"inline constexpr uintptr_t {key} = 0x{value:x};")
    for key, witness in profile["witnesses"].items():
        data = bytes.fromhex(witness["bytes"])
        lines.append(f'inline constexpr uintptr_t {key}Rva = {witness["rva"]};')
        values = ",".join(f"0x{value:02x}" for value in data)
        lines.append(f"inline constexpr std::array<unsigned char,{len(data)}> {key}{{{values}}};")
    wrapper = bytes.fromhex(profile["witnesses"]["CoreWrapper"]["bytes"])
    wrapper_rva = int(profile["witnesses"]["CoreWrapper"]["rva"], 0)
    offset = int(profile["constants"]["CoreBlockRva"], 0) - wrapper_rva
    block = bytearray(wrapper[offset:offset + 16])
    assert len(block) == 16
    for key, value in (("Original", bytes(block)),):
        lines.append(f'inline constexpr std::array<unsigned char,16> {key}Block{{' +
                     ",".join(f"0x{v:02x}" for v in value) + "};")
    edit = profile["change"]
    edit_offset = int(edit["rva"], 0) - int(profile["constants"]["CoreBlockRva"], 0)
    before, after = bytes.fromhex(edit["expected"]), bytes.fromhex(edit["replacement"])
    assert block[edit_offset:edit_offset + len(before)] == before
    assert len(before) == len(after) == 2
    block[edit_offset:edit_offset + len(after)] = after
    lines.append('inline constexpr std::array<unsigned char,16> EnabledBlock{' +
                 ",".join(f"0x{v:02x}" for v in block) + "};")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(json.loads((ROOT / "native-profile.json").read_text()))
    header = ROOT / "src/native_profile.h"
    if args.check:
        if not header.exists() or header.read_text() != text:
            raise SystemExit("Native profile header is stale")
        print("Native ledger and C++ header match.")
    else:
        header.parent.mkdir(exist_ok=True)
        header.write_text(text, encoding="utf-8")
